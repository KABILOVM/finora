/**
 * Подсказка «похоже на ежедневные траты» по названию категории: еда, дорога, продукты. Только подсказка — флажок сама никогда не ставится.
 * Совпадение по началу слова без регистра и «ё»: «Продукты», «продуктовый магазин», «Такси», «Проезд в маршрутке».
 */
const STEMS = [
  'еда',
  'питан',
  'продукт',
  'магазин',
  'кафе',
  'обед',
  'ужин',
  'завтрак',
  'перекус',
  'кофе',
  'столов',
  'ресторан',
  'фастфуд',
  'вода',
  'хлеб',
  'овощ',
  'фрукт',
  'такси',
  'транспорт',
  'проезд',
  'дорог',
  'маршрутк',
  'автобус',
  'метро',
  'бензин',
  'топлив',
  'парковк',
  'связь',
  'мелоч',
];

const norm = (s: string): string => s.toLocaleLowerCase('ru').replace(/ё/g, 'е');

export function looksDaily(name: string): boolean {
  const words = norm(name).split(/[^\p{L}\p{N}]+/u).filter((w) => w !== '');
  return words.some((w) => STEMS.some((stem) => w.startsWith(stem)));
}
