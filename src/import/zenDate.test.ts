import { describe, expect, it } from 'vitest';
import { parseZenDate } from './zenDate';

const ok = (s: string) => {
  const r = parseZenDate(s);
  return r.ok ? r.date : r.reason;
};

describe('parseZenDate', () => {
  it('ГГГГ-ММ-ДД и ДД.ММ.ГГГГ', () => {
    expect(ok('2026-10-11')).toBe('2026-10-11');
    expect(ok('11.10.2026')).toBe('2026-10-11');
    expect(ok('1.3.2025')).toBe('2025-03-01');
    expect(ok('  2026-10-11  ')).toBe('2026-10-11');
  });

  it('после даты может идти время: берётся дата как написано', () => {
    expect(ok('2024-02-29 13:45:00')).toBe('2024-02-29');
    expect(ok('2024-02-29T13:45:00')).toBe('2024-02-29');
    expect(ok('2024-02-29T23:59:59.999Z')).toBe('2024-02-29');
    expect(ok('2024-02-29T23:30:00+05:00')).toBe('2024-02-29');
    expect(ok('29.02.2024 13:45')).toBe('2024-02-29');
    expect(ok('29.02.2024 13:45:10')).toBe('2024-02-29');
  });

  it('29 февраля — только в високосный год (2000 — високосный, 1900 и 2100 — нет)', () => {
    expect(ok('2024-02-29')).toBe('2024-02-29');
    expect(ok('2000-02-29')).toBe('2000-02-29');
    expect(ok('2023-02-29')).toBe('calendar');
    expect(ok('29.02.2023')).toBe('calendar');
    expect(ok('2100-02-29')).toBe('calendar'); // 2100 не високосный
    expect(ok('1900-02-29')).toBe('calendar');
  });

  it('несуществующие даты', () => {
    for (const s of ['2025-04-31', '31.04.2025', '2025-13-01', '2025-00-10', '2025-01-00', '00.01.2025', '32.01.2025']) {
      expect(ok(s), s).toBe('calendar');
    }
  });

  it('границы сервера: с 2000-01-01 по 2100-01-01', () => {
    expect(ok('2000-01-01')).toBe('2000-01-01');
    expect(ok('2100-01-01')).toBe('2100-01-01');
    expect(ok('1999-12-31')).toBe('range');
    expect(ok('2100-01-02')).toBe('range');
  });

  it('пусто и мусор', () => {
    expect(ok('')).toBe('empty');
    expect(ok('   ')).toBe('empty');
    for (const s of ['вчера', '2024/02/29', '29/02/2024', '24.02.29', '2024-2-9', '20240229', '2024-02-29x', 'NaN', '29.02.24 13:45']) {
      expect(ok(s), s).toBe('format');
    }
  });

  it('конец года и начало года без сдвигов', () => {
    expect(ok('31.12.2025')).toBe('2025-12-31');
    expect(ok('2026-01-01 00:00:00')).toBe('2026-01-01');
  });
});
