import { describe, expect, it } from 'vitest';
import { collectTags } from './knownTags';

const brief = (notes: string[]) => collectTags(notes).map((t) => [t.key, t.label, t.tag, t.count]);

describe('collectTags: метки из заметок', () => {
  it('нет заметок и нет меток — пусто (метка — это # и 2–40 знаков, перед ней пробел или начало)', () => {
    expect(collectTags([])).toEqual([]);
    expect(collectTags(['обед', '', 'цена #5', 'a # b', 'a#b'])).toEqual([]);
  });

  it('считает операции, а не вхождения: метка дважды в одной заметке — одна операция', () => {
    expect(brief(['кофе #Самарканд', 'такси #Самарканд', 'ужин #Самарканд #Самарканд'])).toEqual([['самарканд', 'Самарканд', 'Самарканд', 3]]);
  });

  it('регистр и «ё» не различаются; название — самое частое написание', () => {
    expect(brief(['#Ёлка гирлянда', 'шары #Ёлка', 'мишура #елка'])).toEqual([['елка', 'Ёлка', 'Ёлка', 3]]);
    // «самарканд» один раз, «Самарканд» два: показываем «Самарканд»
    expect(brief(['a #самарканд', 'b #Самарканд', 'c #Самарканд'])).toEqual([['самарканд', 'Самарканд', 'Самарканд', 3]]);
  });

  it('при равенстве написаний — по алфавиту (результат не зависит от порядка заметок)', () => {
    expect(brief(['a #аа', 'b #Аа'])).toEqual(brief(['b #Аа', 'a #аа']));
    expect(brief(['a #аа', 'b #Аа'])[0]?.[2]).toBe('Аа');
  });

  it('подчёркивания в названии — пробелами, но вставляется метка как в заметках', () => {
    expect(brief(['гостиница #Поездка_в_Самарканд'])).toEqual([['поездка_в_самарканд', 'Поездка в Самарканд', 'Поездка_в_Самарканд', 1]]);
  });

  it('порядок: чаще — раньше; при равенстве — по названию', () => {
    const tags = collectTags(['#бета #бета', '#бета', '#альфа', '#альфа', '#гамма']);
    expect(tags.map((t) => [t.label, t.count])).toEqual([
      ['альфа', 2],
      ['бета', 2],
      ['гамма', 1],
    ]);
  });
});
