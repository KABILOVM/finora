import type { CategoryKind } from '@/domain/types';

/**
 * Готовые категории с подкатегориями: «Коммунальные услуги» → свет, вода, газ…; «Продукты» → мясо, овощи, молочное…; «Семья» → дети, супруг(а)…
 * Из них человек выбирает, что завести (мастер первой настройки, «Категории» → «Готовые категории», разовое предложение действующим).
 *
 * Slug у группы и подкатегории — ВЕЧНЫЙ: от него и от userId считается id строки (как у стартовых категорий, см. src/db/seed.ts), поэтому два
 * устройства одного человека заводят одни и те же строки, а не дубли. Переименовывать и переиспользовать slug нельзя; новое — только добавлять.
 *
 * `aka` — как человек мог назвать то же самое у себя («Коммуналка», «Свет», «Жена»): по названиям и синонимам готовая запись сопоставляется
 * с уже имеющимися категориями (см. catalogPlan.ts), чтобы не заводить дубль, а подкатегории — собрать под нужным родителем.
 * Название и синоним не должны повторяться у разных записей одного вида (проверяет catalogData.test.ts).
 */

export interface CatalogChild {
  /** Вечный идентификатор внутри группы, латиницей. */
  slug: string;
  name: string;
  /** Значок: имя из src/components/iconExtraData.ts (GLYPH_CHOICES), записывается как «i:имя». */
  icon: string;
  /** Другие названия того же (для сопоставления с категориями человека). */
  aka?: readonly string[];
  /** Обязательная расходная категория: цели накопления её не урезают. */
  essential?: boolean;
}

export interface CatalogGroup {
  /** Вечный идентификатор, латиницей. */
  slug: string;
  kind: CategoryKind;
  name: string;
  icon: string;
  color: string;
  aka?: readonly string[];
  essential?: boolean;
  /** Входит в набор «по умолчанию»: заранее отмечена в окне выбора. */
  popular?: boolean;
  /** Короткая подсказка в списке: что внутри. */
  hint: string;
  children: readonly CatalogChild[];
}

const child = (slug: string, name: string, icon: string, aka: readonly string[] = [], essential = false): CatalogChild => ({
  slug,
  name,
  icon,
  ...(aka.length > 0 ? { aka } : {}),
  ...(essential ? { essential } : {}),
});

