import type { IsoDate } from '@/domain/types';

/**
 * Когда на «Главной» показывается «Итоги месяца». Отдельным крошечным файлом: главная решает по нему, грузить ли саму карточку
 * (она ленивая и нужна лишь первые дни месяца), и не тянет за собой остальной код итогов в основной файл.
 */

/** Сколько первых дней месяца показываем карточку: с 1-го по 5-е (кто открыл приложение позже, итогов уже не увидит). */
export const MONTHLY_SHOW_DAYS = 5;

/** Показывать ли карточку сегодня: первые дни месяца. */
export const inMonthlyWindow = (today: IsoDate): boolean => Number(today.slice(8, 10)) <= MONTHLY_SHOW_DAYS;
