import { describe, expect, it } from 'vitest';
import { MAX_PARSED_ITEMS, parseShoppingText as parse } from './shoppingText';

const item = (name: string, qtyMilli: number, unit: 'pcs' | 'kg' | 'l') => ({ name, qtyMilli, unit });

describe('разбор продиктованного списка', () => {
  it('с запятыми и числами словами', () => {
    expect(parse('молоко два литра, хлеб три штуки, яблоки полтора килограмма')).toEqual([
      item('Молоко', 2000, 'l'),
      item('Хлеб', 3000, 'pcs'),
      item('Яблоки', 1500, 'kg'),
    ]);
  });

  it('без запятых (так диктует телефон): новая позиция начинается после «название + количество + единица»', () => {
    expect(parse('молоко 2 л хлеб 3 шт яблоки 1,5 кг')).toEqual([item('Молоко', 2000, 'l'), item('Хлеб', 3000, 'pcs'), item('Яблоки', 1500, 'kg')]);
    expect(parse('молоко два литра хлеб три штуки яблоки полтора килограмма')).toHaveLength(3);
  });

  it('количество перед названием: «два литра молока, три килограмма яблок»', () => {
    expect(parse('два литра молока три килограмма яблок')).toEqual([item('Молока', 2000, 'l'), item('Яблок', 3000, 'kg')]);
  });

  it('десятичная запятая — не разделитель позиций', () => {
    expect(parse('яблоки 1,5 кг, груши 0,25 кг')).toEqual([item('Яблоки', 1500, 'kg'), item('Груши', 250, 'kg')]);
  });

  it.each([
    ['сыр 500 г', item('Сыр', 500, 'kg')],
    ['сыр пятьсот грамм', item('Сыр', 500, 'kg')],
    ['сыр сто пятьдесят грамм', item('Сыр', 150, 'kg')],
    ['масло 750 мл', item('Масло', 750, 'l')],
    ['молоко 2л', item('Молоко', 2000, 'l')],
    ['картошка два с половиной килограмма', item('Картошка', 2500, 'kg')],
    ['сахар полкило', item('Сахар', 500, 'kg')],
    ['масло пол-литра', item('Масло', 500, 'l')],
    ['яйца двадцать пять штук', item('Яйца', 25000, 'pcs')],
    ['яйца дюжина', item('Яйца', 12000, 'pcs')],
    ['носки пара', item('Носки', 2000, 'pcs')],
    ['хлеб x3', item('Хлеб', 3000, 'pcs')],
    ['вода × 2', item('Вода', 2000, 'pcs')],
    ['соль', item('Соль', 1000, 'pcs')],
    ['хлеб три', item('Хлеб', 3000, 'pcs')],
  ])('«%s»', (text, want) => {
    expect(parse(text)).toEqual([want]);
  });

  describe('несколько названий подряд, без запятых и количества (телефон не поставил запятых)', () => {
    it('«мука масло» — два товара', () => {
      expect(parse('Мука масло')).toEqual([item('Мука', 1000, 'pcs'), item('Масло', 1000, 'pcs')]);
      expect(parse('мука масло сахар соль').map((i) => i.name)).toEqual(['Мука', 'Масло', 'Сахар', 'Соль']);
    });
    it('прилагательное липнет к существительному: «сливочное масло мука», «хлеб белый молоко»', () => {
      expect(parse('сливочное масло мука').map((i) => i.name)).toEqual(['Сливочное масло', 'Мука']);
      expect(parse('мука белая масло').map((i) => i.name)).toEqual(['Мука белая', 'Масло']);
      expect(parse('хлеб белый молоко').map((i) => i.name)).toEqual(['Хлеб белый', 'Молоко']);
      expect(parse('хлеб белый').map((i) => i.name)).toEqual(['Хлеб белый']);
    });
    it('предлог держит слова вместе: «кофе в зёрнах чай»', () => {
      expect(parse('кофе в зернах чай').map((i) => i.name)).toEqual(['Кофе в зернах', 'Чай']);
    });
    it('название из прошлых покупок остаётся целым', () => {
      expect(parse('сыр моцарелла мука', ['Сыр моцарелла'])).toEqual([item('Сыр моцарелла', 1000, 'pcs'), item('Мука', 1000, 'pcs')]);
      expect(parse('сыр моцарелла мука').map((i) => i.name)).toEqual(['Сыр', 'Моцарелла', 'Мука']);
    });
    it('количество достаётся товару рядом с ним: «мука масло два литра» → масло; «два литра молока масла» → молока', () => {
      expect(parse('мука масло два литра')).toEqual([item('Мука', 1000, 'pcs'), item('Масло', 2000, 'l')]);
      expect(parse('два литра молока масла')).toEqual([item('Молока', 2000, 'l'), item('Масла', 1000, 'pcs')]);
    });
    it('«Ёжик Мёд 1 кг»: два названия, количество у последнего', () => {
      expect(parse('Ёжик Мёд 1 кг')).toEqual([item('Ежик', 1000, 'pcs'), item('Мед', 1000, 'kg')]);
    });
  });

  it('разделители: «и», «ещё», «потом», точка с запятой, перевод строки, точка в конце', () => {
    expect(parse('хлеб и молоко потом сыр ещё чай; кофе\nсахар.').map((i) => i.name)).toEqual(['Хлеб', 'Молоко', 'Сыр', 'Чай', 'Кофе', 'Сахар']);
  });

  it('служебные слова отбрасываются: «надо купить молоко пожалуйста»', () => {
    expect(parse('надо купить молоко пожалуйста')).toEqual([item('Молоко', 1000, 'pcs')]);
  });

  it('дробное количество без единицы не бывает штуками: «полтора» → кг', () => {
    expect(parse('арбуз полтора')).toEqual([item('Арбуз', 1500, 'kg')]);
  });

  it('пустое, пробелы, мусор — пустой список; одни числа без названия — пропуск', () => {
    expect(parse('')).toEqual([]);
    expect(parse('   \n , ; ')).toEqual([]);
    expect(parse('два литра')).toEqual([]);
    expect(parse('123')).toEqual([]);
  });

  it('все количества — целые, в границах сервера; название не длиннее 80', () => {
    const big = parse(`${'я'.repeat(200)} 99999999 кг`);
    expect(big).toHaveLength(1);
    expect(Number.isInteger(big[0]!.qtyMilli)).toBe(true);
    expect(big[0]!.qtyMilli).toBeLessThanOrEqual(1_000_000_000);
    expect([...big[0]!.name].length).toBeLessThanOrEqual(80);
  });

  it('не больше MAX_PARSED_ITEMS позиций', () => {
    const text = Array.from({ length: MAX_PARSED_ITEMS + 50 }, (_, i) => `товар${i}`).join(', ');
    expect(parse(text)).toHaveLength(MAX_PARSED_ITEMS);
  });

  it('любая строка не роняет разбор', () => {
    for (const s of ['\u0000', '😀😀', '1e9 кг', '-5 л', '. . .', 'x', '×', '1/2 кг', 'литр литр литр', 'пол пол']) expect(() => parse(s)).not.toThrow();
  });
});
