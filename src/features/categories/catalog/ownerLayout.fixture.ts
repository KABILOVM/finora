/** Разбирает «родитель › дочка» в список категорий с id вида «expense:Родитель» (для подкатегорий родитель находится по названию). */
function parse(text: string, kind: 'expense' | 'income'): ExistingCategory[] {
  const rows = text.split('\n').map((l) => l.split(' › '));
  const idOf = (name: string) => `${kind}:${name}`;
  return rows.map(([a, b]) => {
    const name = b ?? a ?? '';
    return { id: b === undefined ? idOf(name) : `${kind}:${a}›${b}`, name, kind, parentId: b === undefined ? null : idOf(a ?? ''), archived: false, color: '#123456' };
  });
}

export const OWNER_LAYOUT: ExistingCategory[] = [...parse(EXPENSE, 'expense'), ...parse(INCOME, 'income')];
export const ownerId = (kind: 'expense' | 'income', ...path: string[]): string => (path.length === 1 ? `${kind}:${path[0]}` : `${kind}:${path[0]}›${path[1]}`);
